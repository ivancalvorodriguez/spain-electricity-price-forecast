-- Un día por fila, de enero del primer año con festivos a diciembre del último: más
-- allá no se sabe qué días son festivos, y la vista no lo inventa.
--   holiday_regions: cuántas de las 15 comunidades peninsulares tienen fiesta (las
--     previsiones de ESIOS y el precio son del sistema peninsular: fuera Baleares,
--     Canarias, Ceuta y Melilla).
--   national_holiday: fiesta en las 15.
--   hours: 23 o 25 el día del cambio de hora, en hora de Madrid.
CREATE VIEW calendar_day AS
WITH bounds AS (
    SELECT make_date(extract(year FROM min(day))::int, 1, 1)   AS first_day,
           make_date(extract(year FROM max(day))::int, 12, 31) AS last_day
    FROM holiday
    WHERE scope LIKE 'ES-%'
),
peninsular AS (
    SELECT day, count(*) AS regions
    FROM holiday
    WHERE scope IN ('ES-AN', 'ES-AR', 'ES-AS', 'ES-CB', 'ES-CL', 'ES-CM', 'ES-CT',
                    'ES-EX', 'ES-GA', 'ES-MC', 'ES-MD', 'ES-NC', 'ES-PV', 'ES-RI',
                    'ES-VC')
    GROUP BY day
),
days AS (
    SELECT g::date AS day
    FROM bounds b, generate_series(b.first_day, b.last_day, interval '1 day') AS g
)
SELECT d.day,
       extract(isodow FROM d.day)::smallint                  AS isodow,  -- 1 lunes
       coalesce(p.regions, 0)::smallint                      AS holiday_regions,
       coalesce(p.regions = 15, false)                       AS national_holiday,
       EXISTS (SELECT 1 FROM holiday h
               WHERE h.day = d.day AND h.scope = 'PT')       AS pt_holiday,
       (extract(epoch FROM ((d.day + 1)::timestamp AT TIME ZONE 'Europe/Madrid')
                          - (d.day::timestamp AT TIME ZONE 'Europe/Madrid'))
        / 3600)::smallint                                    AS hours
FROM days d
LEFT JOIN peninsular p ON p.day = d.day;

