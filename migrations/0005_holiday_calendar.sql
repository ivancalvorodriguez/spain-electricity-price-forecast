-- Festivos y calendario: lo que se sabe de cada día antes de que llegue y no se revisa
-- nunca. Con el precio rezagado y el gas, son las únicas variables que pueden entrar
-- en el backtest largo.
--
-- holiday: una fila por día y ámbito. El ámbito es el código ISO 3166-2: ES-AN ... ES-ML
-- para las 17 comunidades y Ceuta y Melilla, y PT para Portugal entero (el mercado
-- diario es ibérico). En España no hay fila «nacional»: un festivo nacional es el que
-- tienen todas las comunidades, y eso lo calcula la vista. Las fiestas locales y las
-- insulares de Canarias quedan fuera; el BOE no las trae día a día.
--
-- España, de las resoluciones anuales de la Dirección General de Trabajo (o de Empleo)
-- con la relación de fiestas laborales, tal como se publicaron (el identificador del
-- BOE va encima de cada año). Si una comunidad cambió después alguna fecha en su
-- boletín, aquí no está. Portugal, los feriados obligatorios del Código do Trabalho
-- (art. 234), con la suspensión de 2013-2015 (Lei 23/2012): sin Corpo de Deus, 5 de
-- outubro, 1 de novembro ni 1 de dezembro. El Carnaval no es feriado obligatorio.
--
-- Cada año nuevo de festivos es una migración nueva, en cuanto salga su BOE (octubre).
CREATE TABLE holiday (
    day    date NOT NULL,
    scope  text NOT NULL,
    name   text NOT NULL,
    PRIMARY KEY (day, scope)
);

